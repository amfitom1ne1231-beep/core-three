/**
 * Сценарий эмулятора Telegram-чата.
 *
 * Показывает бота кафе: бронь, меню и заказ с собой. Это не запись
 * и не видео — человек сам нажимает кнопки и видит, что отвечает бот.
 * Ровно так же выглядит настоящий сценарий, который мы пишем: дерево
 * состояний, из каждого есть выход, тупиков нет.
 *
 * `from` — кто говорит. `reply` — что человек отправит, нажав кнопку:
 * в настоящем Telegram это текст сообщения, поэтому он и пишется
 * от первого лица.
 */

export type TgStep = {
  id: string;
  /** Реплики бота. Приходят по очереди, с паузой на «печатает». */
  bot: string[];
  /** Кнопки под последней репликой. Пусто — разговор закончен. */
  options?: { label: string; reply: string; next: string }[];
  /** Пометка под сообщением: что в этот момент произошло на стороне бизнеса. */
  note?: string;
};

