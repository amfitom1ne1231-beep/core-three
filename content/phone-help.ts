export function phoneHelp(pathname: string, scene: number): PhoneHelp {
  if (pathname === '/') return HOME[Math.max(0, Math.min(scene, HOME.length - 1))];
  return PAGES.find(([test]) => test(pathname))?.[1] ?? SERVICE;
}
