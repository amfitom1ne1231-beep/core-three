/**
 * Раздел «Помощь» (/help). План и решения заказчика — HELP.md.
 *
 * Страница устроена не по разделам сайта, а по тому, с чем человек
 * пришёл: слова «лендинг» он может не знать, а свою беду знает.
 * Тексты — на «вы», короткими фразами, без терминов; где без термина
 * нельзя, он есть в словаре. Цен нет, как и на всём сайте.
 *
 * Что уже написано в других местах сайта — сроки брифа, шаги после
 * заявки, «что нужно от вас», вопросы направлений, — берётся оттуда,
 * а не переписывается: две копии разошлись бы на первой же правке.
 *
 * Тексты пишет разработчик, читает и правит заказчик.
 */

