/**
 * Содержимое демо «Барбершоп: запись в Telegram».
 *
 * Клиент вымышленный: «Бритва», барбершоп на три кресла. Продукт —
 * мини-приложение внутри Telegram: услуга, мастер, свободное время,
 * предоплата. Сайта вокруг нет намеренно: у кофейни продаётся стык
 * сайта, бота и меню, здесь — стык клиента и расписания салона. Поэтому
 * рядом с телефоном стоит то, что в ту же секунду видит владелец.
 *
 * Расписание не нарисовано, а считается: занятость мастеров выращивает
 * `lib/barber.ts` из даты, и окна в приложении — ровно дыры в той же сетке,
 * что стоит в панели владельца.
 */

export type Service = {
  id: string;
  name: string;
  /** Для узкой колонки расписания. */
  short: string;
  note: string;
  /** Длительность, минуты. От неё зависит, сколько окон останется. */
  min: number;
  /** Цена у барбера; у старших мастеров — с надбавкой. */
  price: number;
};

export type Master = {
  id: string;
  name: string;
  /** «у Артёма» — бот пишет по-человечески, а не «мастер: Артём». */
  gen: string;
  role: string;
  years: number;
  /** Надбавка к цене услуги. */
  k: number;
  /** Загрузка дня: у топ-барбера окон меньше — так и бывает. */
  load: number;
  /** Аватар без фото — инициал на градиенте, как в самом Telegram. */
  tone: [string, string];
};

