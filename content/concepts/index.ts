/**
 * Паспорта демо.
 *
 * Демо живут по адресу `/concepts/<slug>` и выглядят как сайт клиента.
 * Здесь лежит только то, что нужно нашей стороне: заголовок вкладки,
 * описание для выдачи и подпись в полосе возврата. Содержимое самого
 * демо — в файле рядом (`status.ts` и далее).
 *
 * `ready` решает, ведёт ли карточка в витрине куда-нибудь. Карточка,
 * которая никуда не ведёт, но выглядит ссылкой, обманывает дважды:
 * сначала обещает, потом ничего не делает.
 */
