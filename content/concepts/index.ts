/**
 * Паспорта демо.
 *
 * Демо живут по адресу `/concepts/<slug>` и выглядят как сайт клиента.
 * Здесь лежит только то, что нужно нашей стороне: заголовок вкладки,
 * описание для выдачи и подпись в полосе возврата. Содержимое самого
 * демо — в файле рядом (`status.ts` и далее).
 *
 * `ready` решает, ведёт ли карточка в витрине куда-нибудь. Карточка,
 * которая никуда не ведёт, но выглядит ссылкой, обманывает дважды:
 * сначала обещает, потом ничего не делает.
 */
export type DemoMeta = {
  slug: string;
  /** Вымышленный клиент: его имя стоит в шапке демо, не наше. */
  client: string;
  /** Домен клиента — им подписан адрес в полосе возврата. */
  domain: string;
  /** Ниша: та же строка, что на карточке витрины. */
  niche: string;
  /** Заголовок вкладки и выдачи. */
  title: string;
  description: string;
  /** Что здесь можно потрогать — одна строка для полосы возврата. */
  hint: string;
};

export const DEMOS: DemoMeta[] = [
  {
    slug: 'status',
    client: 'Лавка',
    domain: 'status.lavka.ru',
    niche: 'Мониторинг',
    title: 'Страница статуса «Лавки»',
    description:
      'Демо страницы статуса: аптайм по каждой системе, история проверок, состояние бэкапов и журнал инцидентов. Сбой можно устроить прямо на странице и посмотреть, как он проходит весь путь.',
    hint: 'Проверки идут вживую — сбой можно устроить самому'
  }
];

export const demoBySlug = (slug: string) => DEMOS.find((d) => d.slug === slug);
