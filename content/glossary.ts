export const GLOSSARY: readonly Word[] = [...WORDS].sort(byAlphabet);

/** Для поиска: регистр, «ё» и лишние пробелы не важны. */
export const fold = (s: string) => s.toLocaleLowerCase('ru').replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();

/**
 * Слова по запросу, от самого точного попадания: запрос — начало самого
 * слова, потом начало другого написания или его части, потом просто
 * встретился в названии или объяснении. Ищут «хост» — первым стоит
 * «Хостинг», а не «Аптайм»; ищут «вёрстка» — сама «Вёрстка», а не
 * «Адаптив» с его «адаптивной вёрсткой».
 */
export function findWords(query: string, words: readonly Word[] = GLOSSARY): Word[] {
  const q = fold(query);
  if (!q) return [...words];
  const rank = (w: Word) => {
    const names = [w.term, ...(w.aka ?? [])].map(fold);
    if (fold(w.term).startsWith(q)) return 0;
    if (names.some((n) => n.startsWith(q) || n.split(/[\s-]/).some((part) => part.startsWith(q)))) return 1;
    if (names.some((n) => n.includes(q)) || fold(w.text).includes(q)) return 2;
    return -1;
  };
  return words
    .map((w) => ({ w, r: rank(w) }))
    .filter((x) => x.r >= 0)
    .sort((a, b) => a.r - b.r)
    .map((x) => x.w);
}
