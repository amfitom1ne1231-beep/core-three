import { Onest } from 'next/font/google';

/**
 * Шрифт сайта. Объявлен здесь, а не в корневой раскладке: next/font
 * предзагружает шрифт на всех страницах той раскладки, где он объявлен,
 * и из корня Onest ехал в каждое демо концепта, где не используется
 * ни разу. Отсюда его берут только оболочка сайта и мобильное меню
 * (оно лежит порталом в body, мимо оболочки).
 *
 * Onest переменный — так он и был записан в брифе. Без `weight` next/font
 * берёт один файл на подмножество вместо четырёх статических начертаний:
 * четырнадцать woff2 на странице превращаются в шесть, и прелоадер,
 * который ждёт document.fonts.ready, снимается раньше.
 */
export const onest = Onest({
  subsets: ['latin', 'cyrillic'],
  variable: '--font-onest',
  display: 'swap'
});

/** То же, что `.font-sans`, — для узлов, у которых переменная своя. */
export const SITE_FONT = 'var(--font-onest), system-ui, sans-serif';
