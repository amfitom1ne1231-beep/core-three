const DAY = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'];

export const clock = (min: number) => `${Math.floor(min / 60)}:${String(min % 60).padStart(2, '0')}`;

/** «час», «30 минут», «1 ч 30 мин» — как сказал бы человек. */
export function span(min: number) {
  if (min === 60) return 'час';
  if (min < 60) return `${min} мин`;
  return min % 60 ? `${Math.floor(min / 60)} ч ${min % 60} мин` : `${min / 60} ч`;
}

/** «пн–пт» для подряд идущих дней, иначе перечислением: «пн, ср, пт». */
export function daysLabel(days: number[]) {
  // неделя читается с понедельника: воскресенье — в конец
  const week = [...days].sort((a, b) => ((a + 6) % 7) - ((b + 6) % 7));
  const run = week.every((d, i) => i === 0 || (d + 6) % 7 === ((week[i - 1]! + 6) % 7) + 1);
  if (week.length === 7) return 'каждый день';
  return run && week.length > 2 ? `${DAY[week[0]!]}–${DAY[week[week.length - 1]!]}` : week.map((d) => DAY[d]).join(', ');
}

