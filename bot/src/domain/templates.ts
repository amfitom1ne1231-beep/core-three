/**
 * Шаблоны этапов по направлениям. Проект получает их при создании,
 * дальше этапы правятся в самом проекте — шаблон не закон, а начало.
 *
 * Сайт и бот — по решению заказчика; магазин и мониторинг заказчик
 * оставил «свои» — здесь предложение студии, его легко поправить.
 */
export const STAGE_TEMPLATES: Record<string, readonly string[]> = {
  sites: ['Бриф', 'Прототип', 'Дизайн', 'Разработка', 'Запуск', 'Поддержка'],
  ecommerce: ['Бриф', 'Прототип', 'Дизайн', 'Каталог и корзина', 'Оплата и доставка', 'Запуск', 'Поддержка'],
  bots: ['Сценарий', 'Сборка', 'Интеграции', 'Запуск'],
  monitoring: ['Подключение сайтов', 'Настройка проверок', 'Страница статуса', 'Сопровождение']
};

/** Направление не названо («Общая», «Концепты») — три шага, которые есть у любой работы. */
const FALLBACK = ['Бриф', 'Работа', 'Сдача'] as const;

export const stagesFor = (kind: string): readonly string[] => STAGE_TEMPLATES[kind] ?? FALLBACK;

/** Что делаем — в единственном числе, для названия проекта: «Сайт — Анна». */
export const KIND_NOUN: Record<string, string> = {
  sites: 'Сайт',
  ecommerce: 'Магазин',
  bots: 'Бот',
  monitoring: 'Мониторинг'
};

export const projectTitle = (kind: string, client: string) => `${KIND_NOUN[kind] ?? 'Проект'} — ${client}`;
